USE pc

SELECT l.model, l.code, l.screen FROM laptop AS l
GROUP BY l.model, l.code, l.screen
HAVING (l.screen = 11 AND l.model IN (SELECT l2.model FROM laptop AS l2
WHERE l2.screen = 15)) OR (l.screen = 15 AND l.model IN (SELECT l3.model FROM laptop AS l3
WHERE l3.screen = 11))

--2
SELECT DISTINCT pc.model FROM pc
JOIN product AS p ON pc.model = p.model
WHERE pc.price < (SELECT MIN(l.price) FROM laptop AS l
JOIN product AS p2 ON l.model = p2.model
WHERE p2.maker = p.maker)

--3
SELECT pc.model, AVG(pc.price) AS avg_price FROM pc
JOIN product AS p ON pc.model = p.model
GROUP BY pc.model, p.maker
HAVING AVG(pc.price) < (SELECT MIN(l.price) FROM laptop AS l
JOIN product AS p2 ON l.model = p2.model
WHERE p2.maker = p.maker)

