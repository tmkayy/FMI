SELECT DISTINCT o.SHIP FROM OUTCOMES AS o
WHERE o.SHIP LIKE 'C%' OR  o.SHIP LIKE 'K%' 

--2
SELECT s.NAME, c.COUNTRY  FROM SHIPS AS s
LEFT JOIN CLASSES AS c ON s.CLASS = c.CLASS
LEFT JOIN OUTCOMES AS o ON o.SHIP = s.NAME
WHERE o.RESULT <> 'sunk' OR o.RESULT IS NULL

--3
SELECT c.COUNTRY, ISNULL(COUNT(o.RESULT), 0) AS num_sunk_ships FROM CLASSES AS c
LEFT JOIN SHIPS AS s ON s.CLASS = c.CLASS
LEFT JOIN OUTCOMES AS o ON o.SHIP = s.NAME
GROUP BY c.COUNTRY, o.RESULT
HAVING o.RESULT = 'sunk' OR (o.RESULT IS NULL AND c.COUNTRY NOT IN 
(SELECT c2.COUNTRY FROM CLASSES AS c2
JOIN SHIPS AS s2 ON s2.CLASS = c2.CLASS
JOIN OUTCOMES AS o2 ON o2.SHIP = s2.NAME
WHERE o2.RESULT = 'sunk'))

