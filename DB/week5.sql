SELECT pc1.code, p.maker, (SELECT COUNT(*) FROM pc AS pc2 WHERE pc2.price >= pc1.price
GROUP BY pc2.model
HAVING pc2.model = pc1.model) AS num_pc_higher_price
FROM pc AS pc1
JOIN product AS p ON pc1.model = p.model