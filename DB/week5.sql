SELECT s.STUDIONAME, s.STARNAME, s.num_movies
FROM (
    SELECT m.STUDIONAME, ss.STARNAME, COUNT(*) AS num_movies
    FROM MOVIE AS m
    JOIN STARSIN AS ss ON m.TITLE = ss.MOVIETITLE
    GROUP BY m.STUDIONAME, ss.STARNAME
) AS s
WHERE s.num_movies = (
    SELECT MAX(s2.num_movies)
    FROM (
        SELECT m2.STUDIONAME, ss2.STARNAME, COUNT(*) AS num_movies
        FROM MOVIE AS m2
        JOIN STARSIN AS ss2 ON m2.TITLE = ss2.MOVIETITLE
        GROUP BY m2.STUDIONAME, ss2.STARNAME
    ) AS s2
    WHERE s2.STUDIONAME = s.STUDIONAME
)
ORDER BY s.STUDIONAME

